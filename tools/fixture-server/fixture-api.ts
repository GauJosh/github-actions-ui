// Fixture-mode API: serves the pinned gha-ui-fixtures corpus, plus clearly labelled SYNTHETIC runs, at
// /__fixtures/api with GitHub-shaped routes: repositories, workflows, paginated and filtered run lists,
// runs, jobs, workflow files (Contents API) and job logs with HEAD and explicit byte ranges.
// Read-only, local only, and never contacts GitHub. Refuses to serve anything if the prepared fixtures do
// not match the lockfile.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import type { IncomingMessage, ServerResponse } from "node:http";
import { join } from "node:path";
import { gunzipSync } from "node:zlib";
import { NOT_PREPARED, fixtureDir, verifyFixtures } from "../fixtures/fixtures.ts";
import { parseLock } from "../fixtures/lockfile.ts";
import { SYNTHETIC_LARGE, syntheticJobs, syntheticLog, syntheticRun } from "./synthetic.ts";
import { EMPTY_REPO, LARGE_LOG_WORKFLOW, SYNTHETIC_OWNER, SYNTHETIC_REPO, largeLogRunExtras, syntheticGraphRuns } from "./synthetic-graphs.ts";
import { ENTERPRISE_OWNER, ENTERPRISE_REPO, enterpriseRuns, gallery } from "./enterprise.ts";

export const FIXTURE_PREFIX = "/__fixtures";

type RunJson = Record<string, unknown> & {
  id: number;
  status: string;
  conclusion: string | null;
  head_branch: string | null;
  event: string;
  workflow_id?: number;
  name?: string | null;
  path?: string;
  head_sha: string;
  created_at?: string;
};
type LogSource = { size: number; read(start: number, end: number): Buffer } | { missing: string } | { gone: string };
/** An earlier attempt of a run: its run object and jobs, or the error its jobs endpoint answers with. */
type FixtureAttempt = { run: RunJson; jobs(): string | object; jobsError?: { status: number; message: string } };
type FixtureRun = {
  owner: string;
  repo: string;
  run: RunJson;
  jobs(): string | object;
  workflow(): string | { status: number; message: string } | null;
  /** Other files readable at the run's commit (called workflows, the phase file). */
  files?: Map<string, string>;
  /** Earlier attempts by number (the latest attempt is `run` and `jobs`). */
  attempts?: Map<number, FixtureAttempt>;
  approvals?: unknown[];
  pending?: unknown[];
};
/** `external`: files of repositories without runs (e.g. shared workflows), by "owner/repo@sha", then path. */
type Corpus = {
  runs: Map<number, FixtureRun>;
  logs: Map<number, () => LogSource>;
  repos: Record<string, unknown>[];
  gallery: unknown;
  external: Map<string, Map<string, string | { status: number; message: string }>>;
};

const REAL_DESCRIPTION = "Real runs captured from GitHub (pinned fixture corpus)";
const SYNTHETIC_DESCRIPTION = "SYNTHETIC runs generated by the fixture server: not real GitHub data";
const ENTERPRISE_DESCRIPTION = "SYNTHETIC enterprise CI/CD scenarios (demo gallery): not real GitHub data";

function loadCorpus(root: string, decompress: (jobId: number, path: string) => Buffer): Corpus {
  const runs = new Map<number, FixtureRun>();
  const logs = new Map<number, () => LogSource>();

  for (const ownerRepo of readdirSync(root)) {
    const [owner, repo] = ownerRepo.split("__") as [string, string];
    for (const id of readdirSync(join(root, ownerRepo))) {
      const dir = join(root, ownerRepo, id);
      const manifest = JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8")) as { logs: Record<string, string> };
      const numbers = readdirSync(join(dir, "attempts")).map(Number).sort((a, b) => b - a);
      const latest = numbers[0]!;
      const run = JSON.parse(readFileSync(join(dir, "run.json"), "utf8")) as RunJson;
      // The corpus captured each attempt's jobs, but only the latest run object. An earlier attempt's run object is
      // the captured run with that attempt's number, and its status and conclusion taken from that attempt's jobs.
      const attempts = new Map<number, FixtureAttempt>();
      for (const n of numbers.slice(1)) {
        const text = readFileSync(join(dir, "attempts", String(n), "jobs.json"), "utf8");
        const parsed = JSON.parse(text) as { jobs: { conclusion: string | null; started_at: string | null }[] } | { conclusion: string | null; started_at: string | null }[];
        const list = Array.isArray(parsed) ? parsed : parsed.jobs;
        const order = ["failure", "cancelled", "timed_out", "success", "skipped"];
        const conclusion = order.find((c) => list.some((j) => j.conclusion === c)) ?? null;
        const started = list.map((j) => j.started_at).filter((t): t is string => !!t).sort()[0];
        attempts.set(n, { run: { ...run, run_attempt: n, status: "completed", conclusion, ...(started && { run_started_at: started }) }, jobs: () => text });
      }
      runs.set(Number(id), {
        owner,
        repo,
        run,
        jobs: () => readFileSync(join(dir, "attempts", String(latest), "jobs.json"), "utf8"),
        workflow: () => (existsSync(join(dir, "workflow.yml")) ? readFileSync(join(dir, "workflow.yml"), "utf8") : null),
        attempts,
      });
      for (const [jobId, status] of Object.entries(manifest.logs)) {
        const path = join(dir, "logs", `${jobId}.log.gz`);
        logs.set(Number(jobId), () => {
          if (!existsSync(path)) return { missing: `Log not captured (${status})` };
          const data = decompress(Number(jobId), path);
          return { size: data.byteLength, read: (s, e) => data.subarray(s, e) };
        });
      }
    }
  }

  // Synthetic runs, all under fixtures/synthetic.
  const largeExtras = largeLogRunExtras();
  delete largeExtras.jobId;
  runs.set(SYNTHETIC_LARGE.runId, {
    owner: SYNTHETIC_OWNER,
    repo: SYNTHETIC_REPO,
    run: { ...syntheticRun.run, ...largeExtras } as RunJson,
    jobs: syntheticJobs,
    workflow: () => LARGE_LOG_WORKFLOW,
  });
  logs.set(SYNTHETIC_LARGE.jobId, () => ({ size: SYNTHETIC_LARGE.bytes, read: syntheticLog }));
  for (const s of syntheticGraphRuns()) {
    runs.set(s.run.id, {
      owner: SYNTHETIC_OWNER,
      repo: SYNTHETIC_REPO,
      run: s.run as RunJson,
      jobs: () => ({ total_count: s.jobs.length, jobs: s.jobs }),
      workflow: () => s.workflow,
      ...(s.attempts && { attempts: new Map([...s.attempts].map(([n, a]) => [n, { run: a.run as RunJson, jobs: () => ({ total_count: a.jobs.length, jobs: a.jobs }) }])) }),
    });
    for (const job of s.jobs) {
      const text = s.logs.get(job.id);
      logs.set(job.id, () => (text === undefined ? { missing: "No log for this job (skipped or not finished)" } : { size: Buffer.byteLength(text), read: (a, b) => Buffer.from(text).subarray(a, b) }));
    }
  }

  // SYNTHETIC enterprise CI/CD scenarios, under fixtures/enterprise.
  const enterprise = enterpriseRuns();
  const external: Corpus["external"] = new Map();
  for (const e of enterprise) {
    for (const [at, files] of e.external) external.set(at, files);
    runs.set(e.run.id, {
      owner: ENTERPRISE_OWNER,
      repo: ENTERPRISE_REPO,
      run: e.run as RunJson,
      jobs: () => ({ total_count: e.jobs.length, jobs: e.jobs }),
      workflow: () => e.files.get(e.run.path) ?? null,
      files: e.files,
      approvals: e.approvals,
      pending: e.pending,
      attempts: new Map(
        (e.attempts ?? []).map((a) => [
          a.run.run_attempt as number,
          {
            run: a.run as RunJson,
            jobs: () => ({ total_count: a.jobs.length, jobs: a.jobs }),
            ...(a.jobsError && { jobsError: { status: a.jobsError, message: "[synthetic] Server Error" } }),
          },
        ]),
      ),
    });
    for (const { jobs, logs: texts, expired } of [{ jobs: e.jobs, logs: e.logs, expired: false }, ...(e.attempts ?? []).map((a) => ({ jobs: a.jobs, logs: a.logs, expired: Boolean(a.logsExpired) }))]) {
      for (const job of jobs) {
        const text = texts.get(job.id as number);
        logs.set(job.id as number, () =>
          expired && text !== undefined
            ? { gone: "[synthetic] The log for this job has expired." }
            : text === undefined
              ? { missing: "No log for this job (skipped, waiting or not finished)" }
              : { size: Buffer.byteLength(text), read: (a, b) => Buffer.from(text).subarray(a, b) },
        );
      }
    }
  }

  const repoMap = new Map<string, Record<string, unknown>>();
  for (const r of runs.values()) {
    const full = `${r.owner}/${r.repo}`;
    const pushed = String(r.run.created_at ?? "");
    const existing = repoMap.get(full);
    if (!existing || String(existing.pushed_at) < pushed) {
      repoMap.set(full, {
        full_name: full,
        name: r.repo,
        owner: { login: r.owner },
        private: false,
        description: r.repo === ENTERPRISE_REPO && r.owner === ENTERPRISE_OWNER ? ENTERPRISE_DESCRIPTION : r.owner === SYNTHETIC_OWNER ? SYNTHETIC_DESCRIPTION : REAL_DESCRIPTION,
        pushed_at: pushed,
      });
    }
  }
  repoMap.set(`${SYNTHETIC_OWNER}/${EMPTY_REPO}`, {
    full_name: `${SYNTHETIC_OWNER}/${EMPTY_REPO}`,
    name: EMPTY_REPO,
    owner: { login: SYNTHETIC_OWNER },
    private: false,
    description: "SYNTHETIC repository with no workflow runs",
    pushed_at: "2026-01-01T00:00:00Z",
  });
  const repos = [...repoMap.values()].sort((a, b) => String(b.pushed_at).localeCompare(String(a.pushed_at)));
  return { runs, logs, repos, gallery: gallery(enterprise), external };
}

const send = (res: ServerResponse, status: number, body: unknown, headers: Record<string, string> = {}) => {
  const text = typeof body === "string" ? body : JSON.stringify(body);
  res.writeHead(status, { "Content-Type": "application/json; charset=utf-8", "Cache-Control": "no-store", ...headers });
  res.end(text);
};

/** Parses `bytes=a-b` (the only form the client sends). Returns null for anything else. */
function parseRange(header: string | undefined, size: number): [number, number] | "invalid" | null {
  if (!header) return null;
  const m = /^bytes=(\d+)-(\d+)$/.exec(header);
  if (!m) return "invalid";
  const start = Number(m[1]);
  const end = Math.min(Number(m[2]), size - 1);
  return start <= end ? [start, end] : "invalid";
}

/** Streams in 64 KiB chunks so the client sees a progressive download, as from the real log host. */
function streamBytes(res: ServerResponse, read: (start: number, end: number) => Buffer, start: number, end: number): void {
  let pos = start;
  const pump = () => {
    while (pos <= end) {
      const next = Math.min(end + 1, pos + 64 * 1024);
      const ok = res.write(read(pos, next));
      pos = next;
      if (!ok) {
        res.once("drain", pump);
        return;
      }
    }
    res.end();
  };
  pump();
}

/** GitHub-style page/per_page pagination with an absolute `Link: rel="next"` on this server. */
function paginate<T>(items: T[], url: URL, origin: string): { page: T[]; link?: string } {
  const perPage = Math.min(100, Math.max(1, Number(url.searchParams.get("per_page") ?? 30)));
  const page = Math.max(1, Number(url.searchParams.get("page") ?? 1));
  const slice = items.slice((page - 1) * perPage, page * perPage);
  if (page * perPage >= items.length) return { page: slice };
  const next = new URL(url.pathname + url.search, origin);
  next.searchParams.set("page", String(page + 1));
  return { page: slice, link: `<${next.href}>; rel="next"` };
}

export function createFixtureMiddleware(options: { repoRoot: string; lockPath: string }) {
  let state: { corpus: Corpus } | { error: string } | null = null;
  const decompressed = new Map<number, Buffer>();

  const decompress = (jobId: number, path: string): Buffer => {
    let data = decompressed.get(jobId);
    if (!data) {
      data = gunzipSync(readFileSync(path));
      if (decompressed.size >= 3) decompressed.delete(decompressed.keys().next().value!);
      decompressed.set(jobId, data);
    }
    return data;
  };

  const init = () => {
    if (state) return state;
    try {
      const lock = parseLock(readFileSync(options.lockPath, "utf8"));
      const outRoot = join(options.repoRoot, ".fixtures");
      const problems = verifyFixtures(lock, outRoot);
      state = problems.length
        ? { error: `${NOT_PREPARED} (${problems.length} problem(s), first: ${problems[0]})` }
        : { corpus: loadCorpus(join(fixtureDir(outRoot, lock), "fixtures"), decompress) };
    } catch (error) {
      state = { error: `${NOT_PREPARED} (${(error as Error).message})` };
    }
    return state;
  };

  return (req: IncomingMessage, res: ServerResponse, next: () => void): void => {
    const url = new URL(req.url ?? "/", "http://fixture.local");
    if (!url.pathname.startsWith(FIXTURE_PREFIX + "/")) return next();
    if (req.method !== "GET" && req.method !== "HEAD") return send(res, 405, { message: "Fixture API is read-only" });

    const ready = init();
    if ("error" in ready) return send(res, 503, { message: ready.error });
    const { corpus } = ready;
    const origin = `http://${req.headers.host ?? "localhost"}`;
    const path = url.pathname.slice(FIXTURE_PREFIX.length);

    if (path === "/gallery") return send(res, 200, corpus.gallery);

    if (path === "/api/user/repos") {
      const { page, link } = paginate(corpus.repos, url, origin);
      return send(res, 200, page, link ? { Link: link } : {});
    }

    // Repository search (GitHub's `q` syntax, the subset the app sends): words match the name; `user:` the owner.
    if (path === "/api/search/repositories") {
      const words = (url.searchParams.get("q") ?? "").split(/\s+/).filter(Boolean);
      const owner = words.find((w) => w.startsWith("user:") || w.startsWith("org:"))?.split(":")[1]?.toLowerCase();
      const terms = words.filter((w) => !w.includes(":")).map((w) => w.toLowerCase());
      const items = corpus.repos.filter((r) => {
        const [o, n] = String(r.full_name).toLowerCase().split("/") as [string, string];
        return (!owner || o === owner) && terms.every((t) => n.includes(t));
      });
      const perPage = Math.min(100, Math.max(1, Number(url.searchParams.get("per_page") ?? 30)));
      return send(res, 200, { total_count: items.length, incomplete_results: false, items: items.slice(0, perPage) });
    }
    const exactRepo = /^\/api\/repos\/([^/]+)\/([^/]+)$/.exec(path);
    if (exactRepo) {
      const repo = corpus.repos.find((r) => String(r.full_name).toLowerCase() === `${exactRepo[1]}/${exactRepo[2]}`.toLowerCase());
      return repo ? send(res, 200, repo) : send(res, 404, { message: "Not Found" });
    }

    const repoMatch = /^\/api\/repos\/([^/]+)\/([^/]+)(\/.*)$/.exec(path);
    if (!repoMatch) return send(res, 404, { message: "Not Found" });
    const [, owner, repo, rest] = repoMatch as unknown as [string, string, string, string];
    // Files of synthetic repositories that have no runs (shared reusable workflows), at an exact commit.
    const externalFile = /^\/contents\/(.+)$/.exec(rest);
    const atRef = corpus.external.get(`${owner}/${repo}@${url.searchParams.get("ref")}`);
    if (externalFile && atRef) {
      const file = atRef.get(decodeURIComponent(externalFile[1]!));
      if (file === undefined) return send(res, 404, { message: "Not Found" });
      if (typeof file !== "string") return send(res, file.status, { message: file.message });
      const filePath = decodeURIComponent(externalFile[1]!);
      return send(res, 200, { type: "file", encoding: "base64", path: filePath, name: filePath.split("/").at(-1), content: Buffer.from(file, "utf8").toString("base64") });
    }
    if (!corpus.repos.some((r) => r.full_name === `${owner}/${repo}`)) return send(res, 404, { message: "Not Found" });
    const repoRuns = [...corpus.runs.values()]
      .filter((r) => r.owner === owner && r.repo === repo)
      .sort((a, b) => String(b.run.created_at ?? "").localeCompare(String(a.run.created_at ?? "")) || b.run.id - a.run.id);

    if (rest === "/actions/workflows") {
      // Like GitHub, a workflow is named by its file's top-level `name:` (a run's `name` can be its run-name).
      const seen = new Map<number, unknown>();
      for (const r of repoRuns) {
        const { run } = r;
        if (run.workflow_id === undefined || seen.has(run.workflow_id)) continue;
        const file = r.workflow();
        const declared = typeof file === "string" ? /^name:\s*["']?(.+?)["']?\s*$/m.exec(file)?.[1] : undefined;
        seen.set(run.workflow_id, { id: run.workflow_id, name: declared ?? String(run.path ?? run.name), path: run.path, state: "active" });
      }
      return send(res, 200, { total_count: seen.size, workflows: [...seen.values()] });
    }

    let m = /^\/actions(?:\/workflows\/(\d+))?\/runs$/.exec(rest);
    if (m) {
      const workflowId = m[1] ? Number(m[1]) : undefined;
      const status = url.searchParams.get("status");
      const branch = url.searchParams.get("branch");
      const event = url.searchParams.get("event");
      const filtered = repoRuns
        .map((r) => r.run)
        .filter(
          (r) =>
            (workflowId === undefined || r.workflow_id === workflowId) &&
            (!status || r.status === status || r.conclusion === status) &&
            (!branch || r.head_branch === branch) &&
            (!event || r.event === event),
        );
      const { page, link } = paginate(filtered, url, origin);
      return send(res, 200, { total_count: filtered.length, workflow_runs: page }, link ? { Link: link } : {});
    }

    // One attempt of a run, and its jobs (GitHub: GET …/runs/{id}/attempts/{n} and …/attempts/{n}/jobs).
    m = /^\/actions\/runs\/(\d+)\/attempts\/(\d+)(\/jobs)?$/.exec(rest);
    if (m) {
      const run = corpus.runs.get(Number(m[1]));
      if (!run || run.owner !== owner || run.repo !== repo) return send(res, 404, { message: "Not Found" });
      const n = Number(m[2]);
      const latest = Number(run.run.run_attempt ?? 1);
      if (n === latest) return send(res, 200, m[3] ? run.jobs() : run.run);
      const attempt = run.attempts?.get(n);
      if (!attempt) return send(res, 404, { message: "Not Found" });
      if (!m[3]) return send(res, 200, attempt.run);
      if (attempt.jobsError) return send(res, attempt.jobsError.status, { message: attempt.jobsError.message });
      return send(res, 200, attempt.jobs());
    }

    m = /^\/actions\/runs\/(\d+)(\/jobs|\/approvals|\/pending_deployments)?$/.exec(rest);
    if (m) {
      const run = corpus.runs.get(Number(m[1]));
      if (!run || run.owner !== owner || run.repo !== repo) return send(res, 404, { message: "Not Found" });
      if (m[2] === "/approvals") return send(res, 200, run.approvals ?? []);
      if (m[2] === "/pending_deployments") return send(res, 200, run.pending ?? []);
      return send(res, 200, m[2] ? run.jobs() : run.run);
    }

    m = /^\/contents\/(.+)$/.exec(rest);
    if (m) {
      const filePath = decodeURIComponent(m[1]!);
      const ref = url.searchParams.get("ref");
      const atRef = repoRuns.filter((r) => r.run.head_sha === ref);
      const file = atRef.find((r) => r.run.path === filePath)?.workflow() ?? atRef.map((r) => r.files?.get(filePath)).find((f) => f !== undefined);
      if (!file) return send(res, 404, { message: "Not Found" });
      if (typeof file !== "string") return send(res, file.status, { message: file.message });
      const content = Buffer.from(file, "utf8").toString("base64").replace(/.{60}/g, "$&\n");
      return send(res, 200, { type: "file", encoding: "base64", path: filePath, name: filePath.split("/").at(-1), content });
    }

    // Commits between two runs' commits (GitHub: GET …/compare/{base}...{head}). SYNTHETIC: both commits must be
    // run commits of this repository; the commits in between are generated and clearly labelled.
    m = /^\/compare\/([0-9a-f]{40})\.\.\.([0-9a-f]{40})$/.exec(rest);
    if (m) {
      const [, baseSha, headSha] = m as unknown as [string, string, string];
      const at = (sha: string) => repoRuns.find((r) => r.run.head_sha === sha)?.run;
      const b = at(baseSha);
      const h = at(headSha);
      if (!b || !h) return send(res, 404, { message: "Not Found" });
      if (baseSha === headSha) return send(res, 200, { status: "identical", ahead_by: 0, behind_by: 0, total_commits: 0, commits: [], html_url: `https://github.com/${owner}/${repo}/compare/${baseSha}...${headSha}` });
      const ahead = String(h.created_at ?? "") >= String(b.created_at ?? "");
      const commits = ahead
        ? [1, 2].map((i) => ({
            sha: createHash("sha1").update(`${baseSha}-${headSha}-${i}`).digest("hex"),
            commit: { message: `[synthetic] Commit ${i} between the two runs`, author: { name: "synthetic-user", date: h.created_at } },
          }))
        : [];
      return send(res, 200, {
        status: ahead ? "ahead" : "behind",
        ahead_by: commits.length,
        behind_by: ahead ? 0 : 2,
        total_commits: commits.length,
        commits,
        html_url: `https://github.com/${owner}/${repo}/compare/${baseSha}...${headSha}`,
      });
    }

    m = /^\/actions\/jobs\/(\d+)\/logs$/.exec(rest);
    if (m) {
      const source = corpus.logs.get(Number(m[1]))?.();
      if (!source) return send(res, 404, { message: "Not Found" });
      if ("missing" in source) return send(res, 404, { message: source.missing });
      if ("gone" in source) return send(res, 410, { message: source.gone });
      const { size, read } = source;
      const range = parseRange(req.headers.range, size);
      if (range === "invalid") return send(res, 416, { message: "Range Not Satisfiable" }, { "Content-Range": `bytes */${size}` });
      const [start, end] = range ?? [0, size - 1];
      res.writeHead(range ? 206 : 200, {
        "Content-Type": "text/plain; charset=utf-8",
        "Content-Length": String(end - start + 1),
        "Accept-Ranges": "bytes",
        "Cache-Control": "no-store",
        ...(range ? { "Content-Range": `bytes ${start}-${end}/${size}` } : {}),
      });
      if (req.method === "HEAD" || size === 0) return void res.end();
      return streamBytes(res, read, start, end);
    }

    return send(res, 404, { message: "Not Found" });
  };
}
