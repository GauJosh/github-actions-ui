type Instance = { apiName: string; def: JobDef; needs: string[] };

function expand(main: WorkflowSpec, called: WorkflowSpec[]): Instance[] {
  const byPath = new Map(called.map((w) => [`./${w.path}`, w]));
  const names = new Map<string, string[]>(); // job id (top level) -> API names of all its jobs
  const out: Instance[] = [];
  const legs = (base: string, def: JobDef) => (def.matrix ? def.matrix.values.map((v) => `${base} (${v})`) : [base]);
  for (const job of main.jobs) {
    const deps = (job.needs ?? []).flatMap((n) => names.get(n) ?? []);
    if (job.uses) {
      const inner = byPath.get(job.uses)!;
      const innerNames = new Map<string, string[]>();
      for (const ij of inner.jobs) {
        const innerDeps = ij.needs?.length ? ij.needs.flatMap((n) => innerNames.get(n) ?? []) : deps;
        const api = legs(`${job.id} / ${ij.id}`, ij);
        innerNames.set(ij.id, api);
        for (const a of api) out.push({ apiName: a, def: ij, needs: innerDeps });
      }
      names.set(job.id, [...innerNames.values()].flat());
    } else {
      const api = legs(job.id, job);
      names.set(job.id, api);
      for (const a of api) out.push({ apiName: a, def: job, needs: deps });
    }
  }
  return out;
}

type JobState = { status: string; conclusion: string | null; start?: number; end?: number; failStep?: string; runningStep?: boolean; absent?: boolean; failedUpstream?: boolean };

function simulate(instances: Instance[], outcome: Outcome): Map<string, JobState> {
  const state = new Map<string, JobState>();
  for (const inst of instances) {
    const deps = inst.needs.map((n) => state.get(n)!);
    const cond = inst.def.if ?? "success()";
    const env = inst.def.environment as Env | undefined;
    if (deps.some((d) => d.absent || d.status !== "completed")) {
      state.set(inst.apiName, { status: "pending", conclusion: null, absent: true });
      continue;
    }
    const directFailed = deps.some((d) => d.conclusion === "failure" || d.conclusion === "cancelled");
    const failedUpstream = directFailed || deps.some((d) => d.failedUpstream);
    const allOk = deps.every((d) => d.conclusion === "success");
    // failure(): any upstream job failed; the rollback guard additionally needs a direct need to have failed.
    const runs = cond.includes("failure()")
      ? failedUpstream && (!cond.includes("contains(needs.*.result, 'failure')") || directFailed)
      : cond.includes("always()")
        ? true
        : allOk;
    const ready = Math.max(0, ...deps.map((d) => d.end ?? 0)) + 6;
    if (!runs) {
      state.set(inst.apiName, { status: "completed", conclusion: "skipped", start: ready, end: ready, failedUpstream });
      continue;
    }
    if (env && outcome.waiting?.includes(env)) {
      state.set(inst.apiName, { status: "waiting", conclusion: null, start: ready });
      continue;
    }
    if (env && outcome.rejected?.includes(env)) {
      // Assumption: a rejected deployment ends its job as failed (GitHub shows the job as failed).
      state.set(inst.apiName, { status: "completed", conclusion: "failure", start: ready, end: ready + 1, failStep: "__rejected", failedUpstream });
      continue;
    }
    if (outcome.running?.includes(inst.apiName)) {
      state.set(inst.apiName, { status: "in_progress", conclusion: null, start: ready, runningStep: true });
      continue;
    }
    const failStep = outcome.fail?.[inst.apiName];
    state.set(inst.apiName, { status: "completed", conclusion: failStep ? "failure" : "success", start: ready, end: ready + durationOf(inst.apiName), failStep, failedUpstream });
  }
  return state;
}

const stepName = (s: StepDef) => s.name ?? (s.uses ? `Run ${s.uses}` : `Run ${s.run}`);

export type EnterpriseRun = {
  scenario: { id: string; title: string; description: string };
  variant: { id: string; label: string };
  run: Record<string, unknown> & { id: number; status: string; conclusion: string | null; head_branch: string; event: string; workflow_id: number; path: string; head_sha: string; created_at: string };
  jobs: Record<string, unknown>[];
  files: Map<string, string>;
  logs: Map<number, string>;
  approvals: unknown[];
  pending: unknown[];
};

function buildRun(s: ScenarioSpec, v: VariantSpec, workflowId: number): EnterpriseRun {
  const base = -v.ago * 60;
  const instances = expand(s.main, s.called);
  const state = simulate(instances, v.outcome);
  const headSha = hash(`${s.id}/${v.id}`);
  const jobs: Record<string, unknown>[] = [];
  const logs = new Map<number, string>();
  instances.forEach((inst, i) => {
    const st = state.get(inst.apiName)!;
    if (st.absent) return; // not created yet: its upstream is still running or waiting
    const id = v.runId * 1000 + i + 1;
    const started = st.start !== undefined && st.status !== "waiting" ? iso(base + st.start) : null;
    const completed = st.end !== undefined ? iso(base + st.end) : null;
    const defs = inst.def.steps ?? [];
    let t = st.start ?? 0;
    let failedAt = -1;
    const steps =
      st.conclusion === "skipped" || st.status === "waiting" || st.failStep === "__rejected"
        ? []
        : [{ name: "Set up job" } as StepDef, ...defs, { name: "Complete job" } as StepDef].map((sd, n, all) => {
            const name = stepName(sd);
            const isLast = n === all.length - 1;
            const failing = st.failStep === name;
            if (failing) failedAt = n;
            const after = failedAt >= 0 && n > failedAt && !isLast;
            const running = st.runningStep && n === all.length - 2;
            const pendingStep = st.runningStep && n >= all.length - 1;
            const s0 = t;
            t += after || pendingStep ? 0 : 4 + (n % 3) * 3;
            return {
              number: n + 1,
              name,
              status: running ? "in_progress" : pendingStep ? "queued" : "completed",
              conclusion: running || pendingStep ? null : failing ? "failure" : after ? "skipped" : "success",
              started_at: pendingStep || after ? null : iso(base + s0),
              completed_at: running || pendingStep || after ? null : iso(base + t),
            };
          });
    jobs.push({
      id,
      run_id: v.runId,
      name: inst.apiName,
      workflow_name: s.main.name,
      head_sha: headSha,
      status: st.status,
      conclusion: st.conclusion,
      created_at: iso(base + Math.max(0, (st.start ?? 0) - 3)),
      started_at: started,
      completed_at: completed,
      html_url: `${HTML}/actions/runs/${v.runId}/job/${id}`,
      run_attempt: 1,
      runner_name: started ? `synthetic-runner-${(i % 7) + 1}` : null,
      labels: ["ubuntu-latest"],
      steps,
    });
    if (st.status === "completed" && st.conclusion !== "skipped") {
      // Shaped like a GitHub runner log, so step-to-log mapping sees the same markers as in live mode: a
      // `##[group]Run …` per step, composite (local) actions' inner steps wrapped in start-action/end-action.
      // Rollback jobs emulate an older runner that does not emit start-action/end-action markers, so their step
      // boundaries are correctly reported as approximate.
      const legacyRunner = inst.def.id.startsWith("rollback");
      const t0 = iso(base + (st.start ?? 0));
      const lines = [
        `${t0} Current runner version: '${legacyRunner ? "2.311.0" : "2.337.0"}'`,
        `${t0} [synthetic] log generated by the GitHub Actions UI fixture server`,
        `${t0} ##[group]Runner Image`,
        `${t0} Image: ubuntu-24.04`,
        `${t0} ##[endgroup]`,
        `${t0} Prepare all required actions`,
        `${t0} Complete job name: ${inst.apiName}`,
      ];
      if (st.failStep === "__rejected") lines.push(`${completed} ##[error]Deployment to ${inst.def.environment} was rejected by a reviewer.`);
      const defOf = new Map(defs.map((d) => [stepName(d), d]));
      for (const step of steps.slice(1, -1)) {
        if (step.conclusion === "skipped" || !step.started_at) continue;
        const def = defOf.get(step.name);
        const at = step.started_at;
        const end = step.completed_at ?? at;
        const failing = step.conclusion === "failure";
        const output = [`${at} ${step.name}: working…`];
        if (failing) {
          output.push(
            `${end} Error: [synthetic] ${step.name} failed in ${inst.apiName}: health check returned 503 for 3 consecutive probes`,
            `${end} ##[error][synthetic] ${step.name} failed: health check returned 503 for 3 consecutive probes`,
            `${end} ##[error]Process completed with exit code 1.`,
          );
        } else output.push(`${end} ${step.name}: done`);
        if (def?.uses) {
          lines.push(`${at} ##[group]Run ${def.uses}`, `${at} with:`, `${at}   environment: ${inst.def.environment ?? "none"}`, `${at} ##[endgroup]`);
          if (def.uses.startsWith("./")) {
            const script = `./scripts/${def.uses.split("/").pop()}.sh`;
            if (!legacyRunner) lines.push(`${at} ##[start-action display=${step.name} (inner step);id=__self.__run]`);
            lines.push(`${at} ##[group]Run ${script}`, `${at} shell: /usr/bin/bash --noprofile --norc -e -o pipefail {0}`, `${at} ##[endgroup]`, ...output);
            if (!legacyRunner) lines.push(`${end} ##[end-action id=__self.__run;outcome=${failing ? "failure" : "success"};conclusion=${failing ? "failure" : "success"}]`);
          } else lines.push(...output);
        } else {
          lines.push(`${at} ##[group]Run ${def?.run ?? step.name}`, `${at} shell: /usr/bin/bash -e {0}`, `${at} ##[endgroup]`, ...output);
        }
        if (failing) break;
      }
      lines.push(`${steps.at(-1)?.started_at ?? completed} Cleaning up orphan processes`);
      logs.set(id, lines.join("\n") + "\n");
    }
  });

  const live = [...state.values()];
  const inFlight = live.some((st) => st.absent || st.status !== "completed");
  const conclusion = inFlight ? null : live.some((st) => st.conclusion === "failure") ? "failure" : "success";
  const ends = live.map((st) => st.end).filter((e): e is number => e !== undefined);
  const files = new Map<string, string>([[s.main.path, workflowYaml(s.main)]]);
  for (const w of s.called) files.set(w.path, workflowYaml(w));
  files.set(
    ".github/actions-ui-phases.yml",
    `# [synthetic] Release phases for GitHub Actions UI (a convention of this app, not a GitHub feature).\n${stringify(
      {
        version: 1,
        workflows: {
          [s.main.path]: {
            phases: s.phases.map((p) => ({ id: p.id, name: p.name, kind: p.kind, ...(p.environment ? { environment: p.environment } : {}), jobs: p.jobs, ...(p.groups ? { groups: p.groups } : {}) })),
          },
        },
      },
      { lineWidth: 0 },
    )}`,
  );
  const reviewer = "release-manager";
  const approvals = [
    ...(v.outcome.approved ?? []).map((e) => ({ state: "approved", comment: `[synthetic] Change CHG-${1000 + v.runId % 1000} approved for ${ENV_NAME[e]}.`, environments: [{ name: e }], user: { login: reviewer } })),
    ...(v.outcome.rejected ?? []).map((e) => ({ state: "rejected", comment: "[synthetic] Rejected: error budget exhausted this week.", environments: [{ name: e }], user: { login: reviewer } })),
  ];
  const pending = (v.outcome.waiting ?? []).map((e) => ({
    environment: { name: e },
    wait_timer: 0,
    current_user_can_approve: false,
    reviewers: [{ type: "Team", reviewer: { name: "release-approvers", slug: "release-approvers" } }],
  }));
  return {
    scenario: { id: s.id, title: s.title, description: s.description },
    variant: { id: v.id, label: v.label },
    run: {
      id: v.runId,
      name: s.main.name,
      display_title: `[synthetic] ${s.title} · ${v.label}`,
      run_number: v.runId % 1000,
      run_attempt: 1,
      workflow_id: workflowId,
      path: s.main.path,
      event: v.event ?? s.main.on,
      head_branch: v.branch ?? "main",
      head_sha: headSha,
      head_commit: { id: headSha, message: `[synthetic] ${s.title}: ${v.label}` },
      status: inFlight ? (live.some((st) => st.status === "waiting") ? "waiting" : "in_progress") : "completed",
      conclusion,
      created_at: iso(base - 5),
      run_started_at: iso(base),
      updated_at: iso(base + Math.max(0, ...ends)),
      actor: { login: "synthetic-user" },
      triggering_actor: { login: "synthetic-user" },
      pull_requests: (v.event ?? s.main.on) === "pull_request" ? [{ number: 1200 + (v.runId % 100) }] : [],
      referenced_workflows: s.called.map((w) => ({ path: `${ENTERPRISE_OWNER}/${ENTERPRISE_REPO}/${w.path}@${headSha}`, sha: headSha, ref: "refs/heads/main" })),
      html_url: `${HTML}/actions/runs/${v.runId}`,
    },
    jobs,
    files,
    logs,
    approvals,
    pending,
  };
}

export function enterpriseRuns(): EnterpriseRun[] {
  const workflowIds = new Map<string, number>();
  return scenarios().flatMap((s) =>
    s.variants.map((v) => {
      if (!workflowIds.has(s.main.path)) workflowIds.set(s.main.path, 9700 + workflowIds.size + 1);
      return buildRun(s, v, workflowIds.get(s.main.path)!);
    }),
  );
}

/** The demo gallery: scenarios and their run variants, in a fixed order. */
export function gallery(runs: EnterpriseRun[]) {
  const order: string[] = [];
  const byScenario = new Map<string, { id: string; title: string; description: string; runs: { runId: number; variant: string; label: string; status: string; conclusion: string | null }[] }>();
  for (const r of runs) {
    if (!byScenario.has(r.scenario.id)) {
      order.push(r.scenario.id);
      byScenario.set(r.scenario.id, { ...r.scenario, runs: [] });
    }
    byScenario.get(r.scenario.id)!.runs.push({ runId: r.run.id, variant: r.variant.id, label: r.variant.label, status: r.run.status, conclusion: r.run.conclusion });
  }
  return { owner: ENTERPRISE_OWNER, repo: ENTERPRISE_REPO, scenarios: order.map((id) => byScenario.get(id)!) };
}
