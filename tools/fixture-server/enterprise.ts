type Env = "dev" | "test" | "stage" | "prod";
const ENV_NAME: Record<Env, string> = { dev: "Dev", test: "Test", stage: "Stage", prod: "Prod" };
const PROTECTED: Env[] = ["stage", "prod"];

/** Deploy, validate and roll back one environment. `after` are the jobs this environment waits for. */
function envJobs(env: Env, after: string[], opts: { services?: string[]; regions?: string[] } = {}): { jobs: JobDef[]; phase: PhaseSpec; exits: string[] } {
  const jobs: JobDef[] = [];
  const roles: Record<string, string> = {};
  const groups: Record<string, string[]> = {};
  const services = opts.services ?? [""];
  const deployIds: string[] = [];
  const validateIds: string[] = [];
  for (const svc of services) {
    const suffix = svc ? `${svc}-${env}` : env;
    const deploy = `deploy-${suffix}`;
    jobs.push({
      id: deploy,
      needs: after,
      environment: env,
      matrix: env === "prod" && opts.regions ? { key: "region", values: opts.regions } : undefined,
      steps: [
        checkout,
        ...(PROTECTED.includes(env) ? [{ name: "Verify change ticket", uses: "acme-org/actions/change-ticket@v1" }] : []),
        { name: `Deploy${svc ? ` ${svc}` : ""} with Helm`, uses: "./.github/actions/deploy-helm" },
        { name: "Wait for rollout", run: "kubectl rollout status deployment" },
      ],
    });
    roles[deploy] = "deploy";
    deployIds.push(deploy);
    const smoke = `smoke-${suffix}`;
    jobs.push({ id: smoke, needs: [deploy], steps: [{ name: "Smoke tests", uses: "./.github/actions/smoke-test" }] });
    roles[smoke] = "validation";
    validateIds.push(smoke);
    if (svc) groups[svc] = [deploy, smoke];
  }
  if (env === "test") {
    jobs.push({ id: "e2e-test", needs: deployIds, steps: [checkout, { name: "End-to-end tests", uses: "./.github/actions/run-tests" }] });
    roles["e2e-test"] = "validation";
    validateIds.push("e2e-test");
  }
  if (env === "stage") {
    jobs.push({ id: "canary-stage", needs: deployIds, steps: [{ name: "Canary analysis", uses: "acme-org/actions/canary-analysis@v4" }] });
    roles["canary-stage"] = "validation";
    validateIds.push("canary-stage");
  }
  const rollback = `rollback-${env}`;
  // GitHub's job-level failure() is true if ANY upstream job failed, so rollbacks are guarded on their own needs.
  jobs.push({
    id: rollback,
    needs: [...deployIds, ...validateIds],
    if: "${{ failure() && contains(needs.*.result, 'failure') }}",
    steps: [{ name: "Roll back with Helm", uses: "./.github/actions/rollback-helm" }],
  });
  roles[rollback] = "recovery";
  const phase: PhaseSpec = { id: env, name: ENV_NAME[env], kind: "deploy", environment: env, jobs: roles, ...(Object.keys(groups).length ? { groups } : {}) };
  return { jobs, phase, exits: validateIds };
}

function cdJobs(start: string[], opts: { services?: string[]; regions?: string[] } = {}) {
  const jobs: JobDef[] = [];
  const phases: PhaseSpec[] = [];
  let after = start;
  for (const env of ["dev", "test", "stage", "prod"] as Env[]) {
    const e = envJobs(env, after, opts);
    jobs.push(...e.jobs);
    phases.push(e.phase);
    after = e.exits;
  }
  jobs.push({ id: "announce", needs: after, steps: [{ name: "Announce release", uses: "acme-org/actions/notify-release@v2" }] });
  phases[phases.length - 1]!.jobs.announce = "other";
  return { jobs, phases };
}

