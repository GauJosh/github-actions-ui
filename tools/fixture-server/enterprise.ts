/** A workflow file as GitHub would read it. */
function workflowYaml(w: WorkflowSpec): string {
  const jobs: Record<string, unknown> = {};
  for (const j of w.jobs) {
    const body: Record<string, unknown> = {};
    if (j.needs?.length) body.needs = j.needs.length === 1 ? j.needs[0] : j.needs;
    if (j.if) body.if = j.if;
    if (j.environment) body.environment = j.environment;
    if (j.uses) {
      body.uses = j.uses;
      body.secrets = "inherit";
    } else {
      body["runs-on"] = "ubuntu-latest";
      if (j.matrix) body.strategy = { matrix: { [j.matrix.key]: j.matrix.values } };
      body.steps = (j.steps ?? []).map((s) => Object.fromEntries(Object.entries(s).filter(([, v]) => v !== undefined)));
    }
    jobs[j.id] = body;
  }
  return `# [synthetic] Generated by the GitHub Actions UI fixture server. Not a real workflow.\n${stringify({ name: w.name, on: w.on, permissions: { contents: "read" }, jobs }, { lineWidth: 0 })}`;
}

