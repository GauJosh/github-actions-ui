function largeGraph(): RunSpec {
  const stages = 12;
  const width = 8;
  const failAt = { stage: 6, job: 3 };
  let yaml = `name: "[synthetic] Large graph"\non: push\njobs:\n`;
  const jobs: JobSpec[] = [];
  for (let s = 0; s < stages; s++) {
    for (let j = 0; j < width; j++) {
      yaml += `  s${s}-j${j}:\n    runs-on: ubuntu-latest\n${s > 0 ? `    needs: gate-${s - 1}\n` : ""}    steps: [{ run: "echo ${s}-${j}" }]\n`;
      const failed = s === failAt.stage && j === failAt.job;
      const after = s > failAt.stage;
      jobs.push({ name: `s${s}-j${j}`, state: after ? "skipped" : failed ? "failure" : "success", start: s * 120 + j, duration: 40 + j * 7 });
    }
    yaml += `  gate-${s}:\n    runs-on: ubuntu-latest\n    needs: [${Array.from({ length: width }, (_, j) => `s${s}-j${j}`).join(", ")}]\n    steps: [{ run: "echo gate" }]\n`;
    jobs.push({ name: `gate-${s}`, state: s >= failAt.stage ? "skipped" : "success", start: s * 120 + 100, duration: 10 });
  }
  return { id: 990000105, title: "[synthetic] Large graph · 12 stages × 8 jobs (fail)", workflowId: 9905, file: "large.yml", event: "push", branch: "main", ago: 200, workflow: yaml, jobs };
}

