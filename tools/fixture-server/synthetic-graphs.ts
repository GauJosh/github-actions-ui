// Deterministic SYNTHETIC runs for fixture mode, served under the clearly named repository
// `fixtures/synthetic`. Every title starts with "[synthetic]". None of this is real GitHub data.
// They cover graph structures the real corpus lacks: parallel CI with needs, staged CD, reusable workflows,
// a single job, a large graph, unreadable workflow files, and a workflow file that does not match its jobs.
import { createHash } from "node:crypto";
import { SYNTHETIC_LARGE } from "./synthetic.ts";

export const SYNTHETIC_OWNER = "fixtures";
export const SYNTHETIC_REPO = "synthetic";
export const EMPTY_REPO = "empty";
const HTML = `https://github.com/${SYNTHETIC_OWNER}/${SYNTHETIC_REPO}`;
const T0 = Date.parse("2026-10-20T10:00:00Z");
const iso = (seconds: number) => new Date(T0 + seconds * 1000).toISOString().replace(".000Z", "Z");
/** Deterministic, realistic-looking commit IDs (SHA-1 of a label); they do not exist in any repository. */
const sha = (n: number) => createHash("sha1").update(`synthetic-${n}`).digest("hex");

type JobSpec = {
  name: string;
  /** "success", "failure", "skipped", "cancelled", or an in-flight status: "in_progress", "queued", "waiting". */
  state: string;
  start?: number;
  duration?: number;
  /** Step names; the last one fails when the job fails. `null` simulates a job with no step metadata. */
  steps?: string[] | null;
  /** Extra output lines, written before the failure lines (e.g. a stack trace). */
  log?: string[];
};

type RunSpec = {
  id: number;
  title: string;
  workflowId: number;
  file: string;
  event: string;
  branch: string;
  /** Minutes before the reference time. */
  ago: number;
  /** Workflow file text, or an HTTP failure for the Contents API. */
  workflow: string | { status: number; message: string };
  jobs: JobSpec[];
  referenced?: { path: string; sha: string; ref: string }[];
};

export type SyntheticJob = Record<string, unknown> & { id: number; name: string; status: string; conclusion: string | null };
export type SyntheticRun = {
  run: Record<string, unknown> & { id: number; status: string; conclusion: string | null; head_branch: string; event: string; workflow_id: number; path: string; head_sha: string; created_at: string };
  jobs: SyntheticJob[];
  workflow: string | { status: number; message: string };
  logs: Map<number, string>;
  /** Earlier attempts by number (the latest attempt is `run` and `jobs`). */
  attempts?: Map<number, { run: SyntheticRun["run"]; jobs: SyntheticJob[] }>;
};

const IN_FLIGHT = new Set(["in_progress", "queued", "waiting"]);

function makeJobs(spec: RunSpec, offset: number): { jobs: SyntheticJob[]; logs: Map<number, string> } {
  const logs = new Map<number, string>();
  const jobs = spec.jobs.map((j, i): SyntheticJob => {
    const id = spec.id * 100 + i + 1;
    const inFlight = IN_FLIGHT.has(j.state);
    const started = j.state === "queued" || j.state === "waiting" ? null : iso(offset + (j.start ?? 0));
    const completed = inFlight ? null : iso(offset + (j.start ?? 0) + (j.state === "skipped" ? 0 : (j.duration ?? 30)));
    const stepNames = j.steps === null ? null : (j.steps ?? ["Run tests"]);
    let t = j.start ?? 0;
    const steps =
      stepNames === null || j.state === "skipped"
        ? []
        : ["Set up job", "Checkout", ...stepNames, "Complete job"].map((name, n, all) => {
            const last = n === all.length - 2;
            const failedHere = j.state === "failure" && last;
            const afterFailure = j.state === "failure" && n === all.length - 1;
            const running = j.state === "in_progress" && last;
            const pending = j.state === "in_progress" && n === all.length - 1;
            const stepStart = iso(offset + t);
            t += 5;
            return {
              number: n + 1,
              name,
              status: running ? "in_progress" : pending || j.state === "queued" || j.state === "waiting" ? "queued" : "completed",
              conclusion: running || pending ? null : failedHere ? "failure" : afterFailure ? "success" : "success",
              started_at: pending ? null : stepStart,
              completed_at: running || pending ? null : iso(offset + t),
            };
          });
    if (!inFlight && j.state !== "skipped") {
      const lines = [`${iso(offset)} Requested labels: ubuntu-latest`, `${iso(offset)} [synthetic] log generated by the fixture server`];
      for (const step of steps.slice(1, -1)) {
        lines.push(`${step.started_at} ##[group]Run ${step.name}`, `${step.started_at} working on ${step.name}…`, `${step.started_at} ##[endgroup]`);
      }
      for (const extra of j.log ?? []) lines.push(`${completed} ${extra}`);
      if (j.state === "failure") lines.push(`${completed} Error: [synthetic] ${j.name} failed: expected 0 failing checks, found 1`, `${completed} ##[error]Process completed with exit code 1.`);
      if (j.state === "cancelled") lines.push(`${completed} ##[error]The operation was canceled.`);
      lines.push(`${completed} Cleaning up orphan processes`);
      logs.set(id, lines.join("\n") + "\n");
    }
    return {
      id,
      run_id: spec.id,
      name: j.name,
      workflow_name: spec.title,
      head_sha: sha(spec.id),
      status: inFlight ? (j.state === "waiting" ? "waiting" : j.state) : "completed",
      conclusion: inFlight ? null : j.state,
      created_at: iso(offset + Math.max(0, (j.start ?? 0) - 5)),
      started_at: started,
      completed_at: completed,
      html_url: `${HTML}/actions/runs/${spec.id}/job/${id}`,
      run_attempt: 1,
      runner_name: inFlight && j.state !== "in_progress" ? null : "synthetic-runner",
      labels: ["ubuntu-latest"],
      steps: stepNames === null ? undefined : steps,
    };
  });
  return { jobs, logs };
}

function makeRun(spec: RunSpec): SyntheticRun {
  const offset = -spec.ago * 60;
  const { jobs, logs } = makeJobs(spec, offset);
  const states = spec.jobs.map((j) => j.state);
  const inFlight = states.some((s) => IN_FLIGHT.has(s));
  const conclusion = inFlight ? null : states.includes("failure") ? "failure" : states.includes("cancelled") ? "cancelled" : "success";
  const ends = jobs.map((j) => j.completed_at as string | null).filter((x): x is string => !!x);
  return {
    run: {
      id: spec.id,
      name: spec.title,
      display_title: spec.title,
      run_number: spec.id % 1000,
      run_attempt: 1,
      workflow_id: spec.workflowId,
      path: `.github/workflows/${spec.file}`,
      event: spec.event,
      head_branch: spec.branch,
      head_sha: sha(spec.id),
      head_commit: { id: sha(spec.id), message: `${spec.title}\n\nSynthetic commit generated by the fixture server.` },
      status: inFlight ? "in_progress" : "completed",
      conclusion,
      created_at: iso(offset - 10),
      run_started_at: iso(offset),
      updated_at: inFlight ? iso(offset + 600) : (ends.sort().at(-1) ?? iso(offset)),
      actor: { login: "synthetic-user" },
      triggering_actor: { login: "synthetic-user" },
      pull_requests: spec.event === "pull_request" ? [{ number: 42 }] : [],
      referenced_workflows: spec.referenced ?? [],
      html_url: `${HTML}/actions/runs/${spec.id}`,
    },
    jobs,
    workflow: spec.workflow,
    logs,
  };
}

