// Repository dashboard in fixture mode: discovery, run list, filters, paging, refresh, empty and error states.
import { expect, test } from "@playwright/test";
import { forbidGitHub } from "./support";

const repoHash = "#/repos/GauJosh/gha-ui-fixtures";

test("repository discovery: list, filter, and open a repository's runs", async ({ page }) => {
  const github = await forbidGitHub(page);
  await page.goto("/?mode=fixtures");
  const repos = page.getByTestId("repo-list");
  await expect(repos.getByRole("link")).toHaveCount(5);
  await expect(repos).toContainText("SYNTHETIC runs generated by the fixture server: not real GitHub data");
  await page.getByLabel("Filter repositories").fill("kubernetes");
  await expect(repos.getByRole("link")).toHaveCount(1);
  await page.getByLabel("Filter repositories").fill("");
  await repos.getByRole("link", { name: /GauJosh\/gha-ui-fixtures/ }).click();
  await expect(page).toHaveURL(new RegExp(`${repoHash}$`));
  await expect(page.getByTestId("runs-count")).toHaveText("Showing 25 of 34 runs.");
  expect(github).toEqual([]);
});

test("an explicit owner/repo opens a repository without listing permission", async ({ page }) => {
  await page.goto("/?mode=fixtures");
  await page.getByLabel("Repository (owner/repo)").fill("not a repo");
  await page.getByRole("button", { name: "Open", exact: true }).click();
  await expect(page.getByText("Enter a repository as OWNER/REPO")).toBeVisible();
  await page.getByLabel("Repository (owner/repo)").fill("fixtures/synthetic");
  await page.getByRole("button", { name: "Open", exact: true }).click();
  await expect(page.getByTestId("run-list")).toContainText("[synthetic] CI · parallel jobs with needs (fail)");
});

test("run list: status shown as text, load more, and refresh fetches again", async ({ page }) => {
  let listRequests = 0;
  page.on("request", (r) => {
    if (r.url().includes("/actions/runs?")) listRequests++;
  });
  await page.goto(`/?mode=fixtures${repoHash}`);
  const list = page.getByTestId("run-list");
  await expect(list.locator("li")).toHaveCount(25);
  // Status is readable without colour: every row carries a text label.
  for (const label of ["Failed", "Succeeded", "Cancelled"]) await expect(list.getByText(label, { exact: true }).first()).toBeVisible();
  // Rows are lightweight: no job or log requests while listing.
  const jobRequests: string[] = [];
  page.on("request", (r) => {
    if (/\/jobs|\/logs|\/contents\//.test(r.url())) jobRequests.push(r.url());
  });
  await page.getByRole("button", { name: "Load 25 more" }).click();
  await expect(list.locator("li")).toHaveCount(34);
  await expect(page.getByTestId("runs-count")).toHaveText("Showing 34 of 34 runs.");
  await expect(page.getByRole("button", { name: "Load 25 more" })).toHaveCount(0);
  const before = listRequests;
  await page.getByRole("button", { name: "Refresh" }).click();
  await expect.poll(() => listRequests).toBeGreaterThan(before);
  expect(jobRequests).toEqual([]);
});

test("filters: status, workflow, event and branch, kept in the URL, with an empty state and reset", async ({ page }) => {
  await page.goto(`/?mode=fixtures${repoHash}`);
  const list = page.getByTestId("run-list");
  await page.getByLabel("Status", { exact: true }).selectOption("failure");
  await expect(page).toHaveURL(/status=failure/);
  await expect(page.getByTestId("runs-count")).toContainText("matching the filters");
  const badges = list.locator(".sbadge");
  const n = await badges.count();
  expect(n).toBeGreaterThan(0);
  for (let i = 0; i < n; i++) await expect(badges.nth(i)).toHaveText(/Failed/);

  await page.getByLabel("Status", { exact: true }).selectOption("");
  await page.getByLabel("Workflow", { exact: true }).selectOption({ label: "s05 cascade skip" });
  await expect(list.locator("li")).toHaveCount(2);

  await page.reload();
  await expect(list.locator("li")).toHaveCount(2);
  await expect(page.getByLabel("Workflow", { exact: true })).toHaveValue(/\d+/);

  await page.getByLabel("Branch", { exact: true }).fill("no-such-branch");
  await page.getByLabel("Branch", { exact: true }).press("Enter");
  await expect(page.getByTestId("runs-empty")).toContainText("No runs match these filters.");
  await page.getByRole("button", { name: "Clear filters" }).click();
  await expect(page.getByTestId("runs-count")).toHaveText("Showing 25 of 34 runs.");

  await page.goto("/?mode=fixtures#/repos/fixtures/synthetic");
  await page.getByLabel("Event", { exact: true }).selectOption("pull_request");
  await expect(page.getByTestId("run-list").locator("li")).toHaveCount(1);
});

test("a repository with no runs has an explicit empty state", async ({ page }) => {
  await page.goto("/?mode=fixtures#/repos/fixtures/empty");
  await expect(page.getByTestId("runs-empty")).toHaveText("This repository has no workflow runs that GitHub still retains.");
});

test("runs are keyboard-selectable and open the run's graph", async ({ page }) => {
  await page.goto("/?mode=fixtures#/repos/fixtures/synthetic");
  const first = page.getByTestId("run-list").getByRole("link").first();
  await first.focus();
  await page.keyboard.press("Enter");
  await expect(page).toHaveURL(/#\/runs\/fixtures\/synthetic\/\d+$/);
  // The run opens on its release overview or execution graph, depending on what its data supports.
  await expect(page.locator("#graph")).toBeVisible();
  await expect(page.getByRole("navigation", { name: "Breadcrumb" })).toContainText("fixtures/synthetic");
});
