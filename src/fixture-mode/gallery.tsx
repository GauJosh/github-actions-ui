// Demo gallery (fixture mode only; compiled out of production builds). Lists the SYNTHETIC enterprise
// scenarios and their run variants. Variants are separate, fixed synthetic runs: choosing one changes what
// is displayed, never any real workflow.
import { useQuery } from "@tanstack/react-query";
import { routeToHash } from "../domain/run-url";
import type { RunRef } from "../domain/types";

type GalleryRun = { runId: number; variant: string; label: string; status: string; conclusion: string | null };
type Scenario = { id: string; title: string; description: string; runs: GalleryRun[] };
type Gallery = { owner: string; repo: string; scenarios: Scenario[] };

function useGallery() {
  return useQuery({
    queryKey: ["fixture-gallery"],
    queryFn: async (): Promise<Gallery> => {
      const response = await fetch("/__fixtures/gallery", { cache: "no-store" });
      if (!response.ok) throw new Error((await response.json().catch(() => ({ message: `HTTP ${response.status}` }))).message);
      return (await response.json()) as Gallery;
    },
    staleTime: Infinity,
    retry: false,
  });
}

const outcome = (r: GalleryRun) =>
  r.status === "waiting" ? "waiting" : r.status !== "completed" ? "in_progress" : r.conclusion === "success" ? "success" : r.conclusion === "failure" ? "failure" : "unknown";
const OUTCOME_TEXT: Record<string, string> = { waiting: "⏸ waiting", in_progress: "◐ running", success: "✓ succeeded", failure: "✕ failed", unknown: "?" };

export function DemoGallery() {
  const gallery = useGallery();
  if (gallery.isPending) return <p className="note">Loading demo scenarios…</p>;
  if (gallery.isError) {
    return (
      <p className="state state-error" role="alert">
        {gallery.error.message}
      </p>
    );
  }
  const g = gallery.data;
  return (
    <section className="panel gallery" aria-labelledby="gallery-heading" data-testid="demo-gallery">
      <header className="panel-head">
        <h2 id="gallery-heading">Demo gallery</h2>
        <span className="tag">synthetic data</span>
      </header>
      <p className="note">
        Enterprise CI/CD scenarios generated by the fixture server ({g.owner}/{g.repo}). Each variant is a fixed synthetic run; choosing one only changes what is shown.
      </p>
      <div className="gallery-grid">
        {g.scenarios.map((s) => (
          <article key={s.id} className="gallery-card" aria-labelledby={`sc-${s.id}`}>
            <h3 id={`sc-${s.id}`}>{s.title}</h3>
            <p className="note">{s.description}</p>
            <ul>
              {s.runs.map((r) => (
                <li key={r.runId}>
                  <a href={routeToHash({ run: { owner: g.owner, repo: g.repo, runId: r.runId } })} data-testid={`variant-${s.id}-${r.variant}`}>
                    {r.label}
                  </a>{" "}
                  <span className={`gallery-outcome o-${outcome(r)}`}>{OUTCOME_TEXT[outcome(r)]}</span>
                </li>
              ))}
            </ul>
          </article>
        ))}
      </div>
    </section>
  );
}

/** Shows which demo scenario and variant is open, with the sibling variants one click away. */
export function GalleryStrip({ run, view }: { run: RunRef; view?: "graph" }) {
  const gallery = useGallery();
  const g = gallery.data;
  if (!g || run.owner !== g.owner || run.repo !== g.repo) return null;
  const scenario = g.scenarios.find((s) => s.runs.some((r) => r.runId === run.runId));
  if (!scenario) return null;
  return (
    <nav className="gallery-strip" aria-label="Demo scenario variants" data-testid="gallery-strip">
      <span className="eyebrow">Demo scenario</span>
      <strong>{scenario.title}</strong>
      <span className="muted">variant:</span>
      <ul>
        {scenario.runs.map((r) => (
          <li key={r.runId}>
            <a
              href={routeToHash({ run: { ...run, runId: r.runId }, view })}
              aria-current={r.runId === run.runId ? "page" : undefined}
              className={r.runId === run.runId ? "current" : ""}
            >
              {r.label}
            </a>
          </li>
        ))}
      </ul>
      <a href="#/" className="muted">
        All scenarios
      </a>
    </nav>
  );
}
